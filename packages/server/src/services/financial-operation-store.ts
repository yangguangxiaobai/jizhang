/**
 * 财务写操作的**重放存储**(`operationId` → 原始 HTTP 结果)。
 *
 * ## 为什么需要它
 *
 * 原生客户端在弱网下最怕的只有一件事:超时之后**不知道自己到底写成功没有**。
 * 重开页面重发一次,如果服务端没有幂等身份,就会多出一笔工资、多一个周期修订。
 * 因此每个新增的财务写操作都带一个 UUID `operationId`,服务端把
 * 方法/资源/请求指纹/状态码/**原始响应体**与领域写入放在**同一个事务**里落盘。
 *
 * ## 三条硬规则
 *
 * 1. **重放先于任何校验。** 命中已有 `operationId` 时直接返回上次的结果,
 *    **不**再跑 CAS / 来源是否存在 / 窗口是否冲突 —— 否则"上次其实成功了"
 *    会变成 409,而那正是最需要幂等的那条路径。实现上表现为:`commit()`
 *    只在没有命中重放时才被调用。
 * 2. **同一 key 不同请求 = 409。** 指纹覆盖方法、资源与规范化后的请求体;
 *    任何一项不同都说明客户端复用了 key 去表达另一件事,必须显式失败。
 * 3. **失败的校验不消耗 key。** `commit()` 抛错时事务整体回滚,即使它已经
 *    写了一部分领域行,也不会留下"这个 key 已经用过"的痕迹。
 *
 * ## 作用域
 *
 * 存储键是 `operation_id`,但读取/比对都要求 `actor_id` 相同:同一台服务器上
 * 属于别人的 `operationId` 一律当作"不存在"(404),不泄露它存在过。
 *
 * ## 规范化
 *
 * 指纹必须对**语义相同**的请求稳定:`{"a":1,"b":2}` 与 `{"b":2,"a":1}` 是同一
 * 请求。因此按 key 排序、`null` 与缺失区分(`null` 保留、缺失丢弃),并对
 * "无序集合"数组(纯字符串 id、或带 `salaryId`/`transactionId`/… 的对象)排序。
 * 数组顺序 **不** 一律排序:有顺序意义的列表(例如用户排列的规则)必须保留原序,
 * 否则两次真正不同的请求会被判成同一个。
 */
import { createHash } from 'node:crypto';
import type { Db } from '../db/index.js';
import {
  FinancialInvalidError,
  FinancialOperationMismatchError,
  FinancialUnavailableError,
} from './financial-errors.js';

export { FinancialOperationMismatchError };

const UUID_PATTERN = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

/**
 * 校验客户端生成的 `operationId`。
 *
 * 接受任意版本的 UUID(v4/v7 皆可),大小写不敏感。**不接受**自增数字、空串或
 * 带内嵌空白的字符串:它们更容易被不同操作"撞"成同一个 key,而重放错误的代价
 * 是把两次不同的写入当成一次,让第二次的意图静默消失。
 */
export function requireFinancialOperationId(value: unknown): string {
  if (typeof value !== 'string' || !UUID_PATTERN.test(value.trim())) {
    throw new FinancialInvalidError(
      'operationId is required and must be a UUID generated by the client for this attempt.',
    );
  }
  return value.trim().toLowerCase();
}

/** 判断一个值能否作为 `operationId`(不抛错的版本,供可选字段使用)。 */
export function isFinancialOperationId(value: unknown): value is string {
  return typeof value === 'string' && UUID_PATTERN.test(value.trim());
}

/** 一次财务写操作的幂等身份 + 指纹输入。 */
export interface FinancialOperationInput {
  /** 客户端生成的 UUID。格式校验由调用方(路由/服务)负责。 */
  readonly operationId: string;
  /** 数据库+用户作用域。同一服务器上不同用户互不可见。 */
  readonly actorId: string;
  /** 大写 HTTP 方法,例如 `POST`。 */
  readonly method: string;
  /** 资源路径,例如 `/api/v1/financial-planning/periods/confirm`。 */
  readonly resource: string;
  /** 规范化前的请求体(可含额外字段,由规范化决定指纹)。 */
  readonly canonicalPayload: unknown;
  /** 写入时间(epoch 毫秒),由调用方注入以便测试确定性。 */
  readonly now: number;
}

/** 领域写入的返回值:状态码 + 原始响应体。 */
export interface FinancialOperationResult<T> {
  readonly statusCode: number;
  readonly response: T;
}

/** 已存储的重放记录(对外 DTO,见 contract 的 `GET FP/operations/:operationId`)。 */
export interface FinancialOperationRecord {
  readonly operationId: string;
  readonly method: string;
  readonly resource: string;
  readonly statusCode: number;
  readonly response: unknown;
  readonly committedAt: number;
}

interface OperationRow {
  readonly operation_id: string;
  readonly actor_id: string;
  readonly method: string;
  readonly resource: string;
  readonly request_hash: string;
  readonly status_code: number;
  readonly response_json: string;
  readonly committed_at: number;
}

/** 数组元素里出现这些键时,该数组被当作**无序集合**。 */
const SET_ELEMENT_KEYS = [
  'salaryId',
  'transactionId',
  'originalTransactionId',
  'categoryId',
  'periodId',
  'operationId',
  'id',
] as const;

/** 规范化数组元素:纯字符串 id 直接排序;带稳定 id 键的对象按该键排序。 */
function canonicalizeArray(value: readonly unknown[]): unknown[] {
  const items = value.map((item) => canonicalize(item));

  const allStrings = items.every((item) => typeof item === 'string');
  if (allStrings) {
    return [...(items as string[])].sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
  }

  const allObjects = items.every(
    (item) => typeof item === 'object' && item !== null && !Array.isArray(item),
  );
  if (allObjects) {
    const records = items as Record<string, unknown>[];
    for (const key of SET_ELEMENT_KEYS) {
      const keyed = records.every((record) => typeof record[key] === 'string');
      if (!keyed) continue;
      return [...records].sort((a, b) => {
        const left = a[key] as string;
        const right = b[key] as string;
        return left < right ? -1 : left > right ? 1 : 0;
      });
    }
  }

  return items;
}

/** 递归规范化:key 排序、`undefined` 视为缺失、`null` 保留。 */
function canonicalize(value: unknown): unknown {
  if (value === null) return null;
  if (Array.isArray(value)) return canonicalizeArray(value);
  if (typeof value === 'object') {
    const record = value as Record<string, unknown>;
    // 无原型对象:JSON 里的 `"__proto__"` 是一个**普通自有键**,
    // 但对 `{}` 赋值会走 setter 改掉原型,随后 `JSON.stringify` 直接丢掉它 ——
    // 两个语义不同的请求就会得到同一个指纹(重放串台)。
    const out: Record<string, unknown> = Object.create(null) as Record<string, unknown>;
    for (const key of Object.keys(record).sort()) {
      const item = record[key];
      // 缺失与 null 是两件事:省略字段表示"不动",显式 null 表示"清空"。
      if (item === undefined) continue;
      out[key] = canonicalize(item);
    }
    return out;
  }
  if (typeof value === 'bigint') return `${value.toString()}n`;
  if (typeof value === 'number' && !Number.isFinite(value)) return String(value);
  // undefined / 函数 / Symbol 在 JSON 里无法表达,统一按 null 处理,保持确定性。
  if (value === undefined || typeof value === 'function' || typeof value === 'symbol') return null;
  return value;
}

/**
 * 规范化后的请求体字符串。同一个语义请求永远得到同一个字符串,
 * 因此可以直接用于指纹与断言的比较。
 */
export function canonicalFinancialPayload(value: unknown): string {
  return JSON.stringify(canonicalize(value));
}

/** 方法 + 资源 + 规范化请求体的 SHA-256 指纹。 */
export function hashFinancialOperation(
  method: string,
  resource: string,
  payload: unknown,
): string {
  const material = `${method.trim().toUpperCase()}\n${resource.trim()}\n${canonicalFinancialPayload(payload)}`;
  return createHash('sha256').update(material, 'utf8').digest('hex');
}

/**
 * 读一条重放记录。别的用户的 key 与不存在的 key 都返回 `undefined`
 * (路由统一 404),这样跨用户探测不到任何东西。
 */
export function getFinancialOperation(
  db: Db,
  operationId: string,
  actorId: string,
): FinancialOperationRecord | undefined {
  const row = db
    .prepare('SELECT * FROM financial_operations WHERE operation_id = ? AND actor_id = ?')
    .get(operationId, actorId) as OperationRow | undefined;
  if (row === undefined) return undefined;

  let response: unknown;
  try {
    response = JSON.parse(row.response_json);
  } catch {
    // 我们自己写的行读不回来 = 存储被外部改坏了。这时**不能**假装"没执行过"
    // 再让客户端重写一遍(那是重复入账),也不能报 500 让人以为是临时故障:
    // 回 503 FINANCIAL_UNAVAILABLE,与"存储的事实坏到无法解释"同一类。
    throw new FinancialUnavailableError();
  }

  return {
    operationId: row.operation_id,
    method: row.method,
    resource: row.resource,
    statusCode: row.status_code,
    response,
    committedAt: row.committed_at,
  };
}

/**
 * 执行一次财务写操作,并把结果登记为可重放的事实。
 *
 * `commit()` 只在**没有**重放命中时被调用;它做的领域写入与随后的登记行在同一个
 * IMMEDIATE 事务里,所以:
 * - 领域写入失败 → 什么都没有发生,`operationId` 仍可再用;
 * - 成功 → 领域行与重放行要么都在,要么都不在。
 */
export function runFinancialOperation<T>(
  db: Db,
  input: FinancialOperationInput,
  commit: () => FinancialOperationResult<T>,
): FinancialOperationResult<T> {
  const method = input.method.trim().toUpperCase();
  const resource = input.resource.trim();
  const requestHash = hashFinancialOperation(method, resource, input.canonicalPayload);

  const run = db.transaction((): FinancialOperationResult<T> => {
    const existing = db
      .prepare('SELECT * FROM financial_operations WHERE operation_id = ?')
      .get(input.operationId) as OperationRow | undefined;

    if (existing !== undefined) {
      // 先判重放,再做任何业务校验(见本文件顶部第 1 条硬规则)。
      if (
        existing.actor_id !== input.actorId ||
        existing.method !== method ||
        existing.resource !== resource ||
        existing.request_hash !== requestHash
      ) {
        throw new FinancialOperationMismatchError(
          'This operationId was already used for a different request. Generate a new operationId instead of reusing this one.',
        );
      }
      let response: T;
      try {
        response = JSON.parse(existing.response_json) as T;
      } catch {
        // 与 `getFinancialOperation` 同一判断:坏行 = 503,不是 500,也绝不能
        // 当成"没发生过"再执行一次领域写入。
        throw new FinancialUnavailableError();
      }
      return { statusCode: existing.status_code, response };
    }

    const result = commit();

    db.prepare(
      `INSERT INTO financial_operations
         (operation_id, actor_id, method, resource, request_hash, status_code, response_json, committed_at)
       VALUES (?, ?, ?, ?, ?, ?, ?, ?)`,
    ).run(
      input.operationId,
      input.actorId,
      method,
      resource,
      requestHash,
      result.statusCode,
      JSON.stringify(result.response ?? null),
      input.now,
    );

    return result;
  });

  return run.immediate();
}
